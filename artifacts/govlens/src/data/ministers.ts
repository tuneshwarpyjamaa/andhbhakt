export interface MinisterProfile {
  name: string;
  title: 'Prime Minister' | 'Cabinet Minister' | 'MoS (Independent Charge)' | 'Minister of State';
  ministry: string;
  party: string;
  since: string;
  education: string;
  /** Hindi translation of education */
  educationHi?: string;
  educationScore: number;
  criminalCases: number;
  seriousCriminalCases?: number;
  criminalCaseNote?: string;
  /** Hindi translation of criminalCaseNote */
  criminalCaseNoteHi?: string;
  affidavitYear?: number;
  wikiTitle?: string;
  assetGrowthPct?: number | null;
  assetGrowthNote?: string;
  /** Hindi translation of assetGrowthNote */
  assetGrowthNoteHi?: string;
  // ── Profile page extensions ──────────────────────────────────────────────
  slug: string;
  controversies?: string[];
  /** Hindi translations of controversies */
  controversiesHi?: string[];
  caseLinks?: { label: string; url: string }[];
  // ── Financial disclosures ─────────────────────────────────────────────────
  /** Total declared assets, crore ₹, latest ECI/RS affidavit */
  declaredAssetsCr?: number;
  /** Total declared assets, crore ₹, previous ECI/RS affidavit */
  declaredAssetsPrevCr?: number;
  declaredAssetsYear?: number;
  declaredAssetsPrevYear?: number;
  /** Official government-allotted residence */
  officialResidence?: string;
  /** RTI / parliamentary-question disclosures on govt spend */
  govtExpenditure?: {
    label: string;
    labelHi?: string;
    value: string;
    period: string;
    periodHi?: string;
    source: string;
    sourceUrl?: string;
  }[];
  /** IDs from CAG_REPORTS relevant to this minister's department(s) */
  cagReportIds?: string[];
}

export function nameToSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/["'()]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

